ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS password_hash TEXT;
ALTER TABLE public.clients ADD COLUMN IF NOT EXISTS username TEXT UNIQUE;

CREATE TABLE IF NOT EXISTS public.client_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT REFERENCES public.clients(id) ON DELETE CASCADE,
    action TEXT NOT NULL,
    stock TEXT NOT NULL,
    price NUMERIC(20, 6),
    target_price NUMERIC(20, 6),
    stop_loss NUMERIC(20, 6),
    message TEXT,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
ALTER TABLE public.client_alerts ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow all actions" ON public.client_alerts FOR ALL USING (true);

CREATE TABLE IF NOT EXISTS public.client_alert_views (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id BIGINT NOT NULL REFERENCES public.client_alerts(id) ON DELETE CASCADE,
    client_id BIGINT NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    dismissed INTEGER NOT NULL DEFAULT 0,
    UNIQUE(alert_id, client_id)
);
ALTER TABLE public.client_alert_views ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow all actions" ON public.client_alert_views FOR ALL USING (true);

CREATE TABLE IF NOT EXISTS public.stock_prices (
    stock TEXT PRIMARY KEY,
    current_price NUMERIC(20, 6) NOT NULL,
    previous_close NUMERIC(20, 6),
    change NUMERIC(20, 6),
    change_pct NUMERIC(20, 6),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);
ALTER TABLE public.stock_prices ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow all actions" ON public.stock_prices FOR ALL USING (true);
